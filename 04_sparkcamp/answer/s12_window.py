# %% [준비] 실행만 하세요 — 이 파일을 열면 맨 처음 한 번 (Shift+Enter)
import os, sys
os.chdir(r"C:\sparkcamp")
os.environ["PYSPARK_PYTHON"] = sys.executable
from pyspark.sql import SparkSession, functions as F
spark = (SparkSession.builder
         .master("local[2]")
         .appName("sparkcamp")
         .config("spark.local.dir", r"C:\sparkcamp\tmp")
         .config("spark.ui.showConsoleProgress", "false")
         .getOrCreate())
spark.sparkContext.setLogLevel("ERROR")
print("Spark", spark.version, "준비 완료")

SCHEMA = """
event_id STRING, card_id STRING, trip_id STRING, tag_type STRING,
station_id STRING, tag_time TIMESTAMP, fare INT, recv_time TIMESTAMP
"""
day = spark.read.schema(SCHEMA).json("data/tags_day.jsonl")
ins = day.filter((F.col("tag_type") == "IN") & F.col("tag_time").isNotNull())
print(day.count(), ins.count())
# ── 결과 ──
# Spark 4.1.3 준비 완료
# 2008 1010


# %% [12-1] 승차 태그에 5분 Tumbling 창을 붙여 다섯 줄 보십시오.
ins.select("event_id", "tag_time", F.window("tag_time", "5 minutes").alias("w")).show(5, truncate=False)
# ── 결과 ──
# +--------+-------------------+------------------------------------------+
# |event_id|tag_time           |w                                         |
# +--------+-------------------+------------------------------------------+
# |E00001  |2026-10-14 07:00:00|{2026-10-14 07:00:00, 2026-10-14 07:05:00}|
# |E00002  |2026-10-14 07:00:01|{2026-10-14 07:00:00, 2026-10-14 07:05:00}|
# |E00003  |2026-10-14 07:00:02|{2026-10-14 07:00:00, 2026-10-14 07:05:00}|
# |E00004  |2026-10-14 07:00:07|{2026-10-14 07:00:00, 2026-10-14 07:05:00}|
# |E00005  |2026-10-14 07:00:20|{2026-10-14 07:00:00, 2026-10-14 07:05:00}|
# +--------+-------------------+------------------------------------------+
# only showing top 5 rows
# → w 칸 안에 {시작, 끝} 이 들어 있습니다. 07:00:00 에 탄 사람은 07:00~07:05 창에 들어갑니다.

# %% [12-2] 5분마다 승차 인원을 세어 시간 순으로 여섯 줄 보십시오.
by5 = ins.groupBy(F.window("tag_time", "5 minutes").alias("w")).count()
by5.orderBy("w").show(6, truncate=False)
# ── 결과 ──
# +------------------------------------------+-----+
# |w                                         |count|
# +------------------------------------------+-----+
# |{2026-10-14 07:00:00, 2026-10-14 07:05:00}|23   |
# |{2026-10-14 07:05:00, 2026-10-14 07:10:00}|24   |
# |{2026-10-14 07:10:00, 2026-10-14 07:15:00}|27   |
# |{2026-10-14 07:15:00, 2026-10-14 07:20:00}|24   |
# |{2026-10-14 07:20:00, 2026-10-14 07:25:00}|27   |
# |{2026-10-14 07:25:00, 2026-10-14 07:30:00}|31   |
# +------------------------------------------+-----+
# only showing top 6 rows

# %% [12-2 바꿔 보기 ①] 창을 5분이 아니라 10분으로 늘리면? — 창 개수와 합계
by10 = ins.groupBy(F.window("tag_time", "10 minutes").alias("w")).count()
print(by5.count(), "개 창 → 합계", by5.agg(F.sum("count")).first()[0])
print(by10.count(), "개 창 → 합계", by10.agg(F.sum("count")).first()[0])
# ── 결과 ──
# 36 개 창 → 합계 1010
# 18 개 창 → 합계 1010
# → 이래서 — 창이 길어지면 창 개수는 반쯤으로 줄고, 합계는 그대로 입니다. Tumbling 은 겹치지 않으니 어떻게 잘라도 한 사람은 한 번만 세어집니다.
# 창 길이는 "얼마나 자주 보고 싶나" 의 문제입니다(12-7 의 Sliding 은 합계가 달라집니다).

# %% [12-3] 창을 start · end 두 칸으로 펼쳐서 보기 좋게 만드십시오.
by5f = by5.select(F.col("w.start").alias("start"), F.col("w.end").alias("end"), "count")
by5f.orderBy("start").show(6)
# ── 결과 ──
# +-------------------+-------------------+-----+
# |              start|                end|count|
# +-------------------+-------------------+-----+
# |2026-10-14 07:00:00|2026-10-14 07:05:00|   23|
# |2026-10-14 07:05:00|2026-10-14 07:10:00|   24|
# |2026-10-14 07:10:00|2026-10-14 07:15:00|   27|
# |2026-10-14 07:15:00|2026-10-14 07:20:00|   24|
# |2026-10-14 07:20:00|2026-10-14 07:25:00|   27|
# |2026-10-14 07:25:00|2026-10-14 07:30:00|   31|
# +-------------------+-------------------+-----+
# only showing top 6 rows
# → 점(.)으로 묶음 안의 칸을 꺼냅니다(w.start). 보고서·화면에는 이 모양으로 내보냅니다.

# %% [12-4] 피크 5분 — 승차가 가장 많았던 5분 창 세 개를 보십시오.
by5f.orderBy(F.col("count").desc(), "start").show(3)
# ── 결과 ──
# +-------------------+-------------------+-----+
# |              start|                end|count|
# +-------------------+-------------------+-----+
# |2026-10-14 08:05:00|2026-10-14 08:10:00|   43|
# |2026-10-14 08:25:00|2026-10-14 08:30:00|   42|
# |2026-10-14 08:30:00|2026-10-14 08:35:00|   42|
# +-------------------+-------------------+-----+
# only showing top 3 rows
# → 8시대 초반에 몰립니다. "가장 붐빈 5분" 이 실시간 대시보드의 첫 화면입니다.

# %% [12-5] 역별 · 5분별 승차 인원을 구하고, 강남(S01)만 08:00~08:30 사이를 보십시오.
st5 = ins.groupBy(F.window("tag_time", "5 minutes").alias("w"), "station_id").count() \
         .select(F.col("w.start").alias("start"), "station_id", "count")
st5.filter((F.col("station_id") == "S01") &
           (F.col("start") >= "2026-10-14 08:00:00") &
           (F.col("start") <  "2026-10-14 08:30:00")) \
   .orderBy("start").show()
# ── 결과 ──
# +-------------------+----------+-----+
# |              start|station_id|count|
# +-------------------+----------+-----+
# |2026-10-14 08:00:00|       S01|    4|
# |2026-10-14 08:05:00|       S01|   11|
# |2026-10-14 08:10:00|       S01|    6|
# |2026-10-14 08:15:00|       S01|    4|
# |2026-10-14 08:20:00|       S01|    2|
# |2026-10-14 08:25:00|       S01|    4|
# +-------------------+----------+-----+
# → groupBy 에 창과 역을 함께 주면 "역별 5분 승차 인원" 입니다. 이것이 프로젝트 2단계의 실시간 집계 결과 한 줄과 정확히 같은 모양입니다.

# %% [12-6] Tumbling 창의 count 를 전부 더해서 승차 수(ins.count())와 같은지 확인하십시오.
print(by5.agg(F.sum("count")).first()[0])
print(ins.count())
# ── 결과 ──
# 1010
# 1010
# → 같습니다. 겹치지 않는 창이라 한 사람이 한 번만 세어졌습니다.

# %% [12-7] 10분 창을 5분마다 미는 Sliding 으로 세고, count 를 전부 더해 보십시오.
slide = ins.groupBy(F.window("tag_time", "10 minutes", "5 minutes").alias("w")).count()
print(slide.agg(F.sum("count")).first()[0])
slide.select(F.col("w.start").alias("start"), F.col("w.end").alias("end"), "count") \
     .orderBy("start").show(4)
# ── 결과 ──
# 2020
# +-------------------+-------------------+-----+
# |              start|                end|count|
