# |2026-10-14 07:10:00|2026-10-14 07:20:00|   51|
# +-------------------+-------------------+-----+
# only showing top 4 rows
# → 합계가 정확히 두 배입니다. 한 사람이 겹치는 창 두 개에 다 들어가기 때문입니다. 첫 창이 06:55 부터인 것도 보십시오 — 07:00 에 탄 사람이
# 들어갈 "최근 10분" 창이 06:55~07:05 부터 있기 때문입니다.

# %% [12-8] 1시간 Tumbling 창으로 세고, STEP 09 의 date_trunc 결과와 같은지 보십시오.
ins.groupBy(F.window("tag_time", "1 hour").alias("w")).count() \
   .select(F.col("w.start").alias("start"), "count").orderBy("start").show()
# ── 결과 ──
# +-------------------+-----+
# |              start|count|
# +-------------------+-----+
# |2026-10-14 07:00:00|  305|
# |2026-10-14 08:00:00|  453|
# |2026-10-14 09:00:00|  252|
# +-------------------+-----+
# → 정시로 자른 것과 같습니다. window 는 date_trunc 의 일반판입니다(15분 · 5분 · 10분 단위도 되고, 겹치게도 된다).

# %% [12-9] 하차 태그를 5분 창으로 세는데, 한 번은 tag_time(댄 시각), 한 번은 recv_time(도착 시각) 기준으로 세어 07:30~07:35 창을
# 비교하십시오.
outs = day.filter((F.col("tag_type") == "OUT") & F.col("tag_time").isNotNull())

def count_at(col_name):
    return (outs.groupBy(F.window(col_name, "5 minutes").alias("w")).count()
                .filter(F.col("w.start") == "2026-10-14 07:30:00")
                .first()["count"])

print("댄 시각 기준  :", count_at("tag_time"))
print("도착 시각 기준:", count_at("recv_time"))
# ── 결과 ──
# 댄 시각 기준  : 16
# 도착 시각 기준: 14
# → 숫자가 다릅니다. 07:32 에 내린 사람의 기록이 08:11 에 도착하면, 도착 시각으로 세는 순간 엉뚱한 창(08:10~08:15) 에 들어갑니다.
# 그래서 집계는 이벤트 시간(tag_time)으로 합니다. def 는 같은 계산을 두 번 쓰려고 만든 작은 함수입니다.

# %% [12-10] 도착이 10분 넘게 늦은 하차 태그가 이벤트 시간 기준 몇 시 창에 있었는지 세어 보십시오.
late = outs.filter(F.unix_timestamp("recv_time") - F.unix_timestamp("tag_time") > 600)
late.groupBy(F.window("tag_time", "1 hour").alias("w")).count() \
    .select(F.col("w.start").alias("start"), "count").orderBy("start").show()
