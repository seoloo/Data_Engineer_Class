# +-------------------+-----+
# → 배치(이미 다 쌓인 파일)에서는 늦게 온 것도 제자리 창에 넣을 수 있습니다. 그런데 실시간에서는 08시 창을 언제 닫아야 할까요? 늦은 엽서를 몇 분까지
