# 12 2008


# %% [06-1] 작은 로그에서 trip_id · tag_type · station_id · fare 만 보십시오.
mini.select("trip_id", "tag_type", "station_id", "fare").show()
# ── 결과 ──
# +-------+--------+----------+----+
# |trip_id|tag_type|station_id|fare|
# +-------+--------+----------+----+
# |   T001|      IN|       S01|   0|
# |   T002|      IN|       S06|   0|
# |   T003|      IN|       S03|   0|
# |   T004|      IN|       S05|   0|
# |   T005|      IN|       S01|   0|
# |   T006|      IN|       S08|   0|
# |   T005|     OUT|       S02|1550|
# |   T003|     OUT|       S04|1550|
# |   T002|     OUT|       S01|1650|
# |   T004|     OUT|       S07|1650|
# |   T001|     OUT|       S03|1650|
# |   T005|     OUT|       S02|1550|
# +-------+--------+----------+----+

# %% [06-2] 작은 로그에서 승차(IN) 만 고르십시오.
mini.filter(F.col("tag_type") == "IN").show()
# ── 결과 ──
# +-------+--------+----+-------------------+----------+-------------------+--------+-------+
# |card_id|event_id|fare|          recv_time|station_id|           tag_time|tag_type|trip_id|
# +-------+--------+----+-------------------+----------+-------------------+--------+-------+
# |   C001|     M01|   0|2026-10-14 08:01:11|       S01|2026-10-14 08:01:10|      IN|   T001|
# |   C002|     M02|   0|2026-10-14 08:03:06|       S06|2026-10-14 08:03:05|      IN|   T002|
# |   C003|     M03|   0|2026-10-14 08:05:01|       S03|2026-10-14 08:05:00|      IN|   T003|
# |   C004|     M04|   0|2026-10-14 08:07:31|       S05|2026-10-14 08:07:30|      IN|   T004|
# |   C005|     M05|   0|2026-10-14 08:09:46|       S01|2026-10-14 08:09:45|      IN|   T005|
# |   C006|     M06|   0|2026-10-14 08:12:01|       S08|2026-10-14 08:12:00|      IN|   T006|
# +-------+--------+----+-------------------+----------+-------------------+--------+-------+
# → 같다는 == 두 개입니다 (MySQL 의 = 하나와 다릅니다). 승차 6건.

# %% [06-3] 같은 일을 where 에 SQL 글자로 써서, 하차(OUT)가 몇 건인지 세십시오.
mini.where("tag_type = 'OUT'").count()
# ── 결과 ──
# 6
# → 6. 하차 5건 + 재전송된 M07 한 건입니다. where 안은 SQL 이라 = 하나를 씁니다.

# %% [06-4] 하차이면서 요금이 1,600원 이상인 것을 고르십시오. 조건마다 괄호를 쓰십시오.
mini.filter((F.col("tag_type") == "OUT") & (F.col("fare") >= 1600)).show()
# ── 결과 ──
# +-------+--------+----+-------------------+----------+-------------------+--------+-------+
# |card_id|event_id|fare|          recv_time|station_id|           tag_time|tag_type|trip_id|
# +-------+--------+----+-------------------+----------+-------------------+--------+-------+
# |   C002|     M09|1650|2026-10-14 08:24:51|       S01|2026-10-14 08:24:50|     OUT|   T002|
# |   C004|     M10|1650|2026-10-14 08:29:01|       S07|2026-10-14 08:29:00|     OUT|   T004|
# |   C001|     M11|1650|2026-10-14 08:31:41|       S03|2026-10-14 08:31:40|     OUT|   T001|
# +-------+--------+----+-------------------+----------+-------------------+--------+-------+
# → & 는 그리고, | 는 또는, ~ 는 아니다.

# %% [06-4 바꿔 보기 ①] 그리고(&) 를 또는(|) 으로 바꾸면? — 승차이거나 요금 1,600 이상
print(mini.filter((F.col("tag_type") == "IN") & (F.col("fare") >= 1600)).count())
print(mini.filter((F.col("tag_type") == "IN") | (F.col("fare") >= 1600)).count())
# ── 결과 ──
# 0
# 9
# → 이래서 — 0 과 9. 승차에는 요금이 0 이라 "둘 다"(&) 맞는 줄은 없고, "둘 중 하나"(|) 면 승차 6 + 요금 1,600 이상 하차 3 =
# 9 입니다. 기호 하나로 결과가 0 이 되기도 합니다 — 조건을 쓰면 세어 보고 말이 되는지 확인하는 습관을 들입니다.

# %% [06-5] 일부러 틀려 보십시오. 06-4 를 괄호 없이 쓰십시오.
mini.filter(F.col("tag_type") == "OUT" & F.col("fare") >= 1600).show()
# ── 결과 (오류 — 일부러 틀린 것) ──
# PySparkValueError: [CANNOT_CONVERT_COLUMN_INTO_BOOL] Cannot convert column into bool: please use '&' for 'and', '|' for 'or', '~' for 'not' when building DataFrame boolean expressions.
# → CANNOT_CONVERT_COLUMN_INTO_BOOL — 메시지가 친절하게 "and 대신 & 를 쓰라" 고 알려 주지만 진짜 원인은 괄호입니다.
# 06-4 처럼 조건마다 괄호를 치면 사라집니다.

# %% [06-6] 강남(S01) 또는 역삼(S02)에서 찍힌 태그만 고르십시오. isin 을 쓰십시오.
mini.filter(F.col("station_id").isin("S01", "S02")).select("event_id", "tag_type", "station_id").show()
# ── 결과 ──
# +--------+--------+----------+
# |event_id|tag_type|station_id|
# +--------+--------+----------+
# |     M01|      IN|       S01|
# |     M05|      IN|       S01|
# |     M07|     OUT|       S02|
# |     M09|     OUT|       S01|
# |     M07|     OUT|       S02|
# +--------+--------+----------+

# %% [06-7] 작은 로그를 태그 시각이 늦은 것부터 세 줄 보십시오.
mini.orderBy(F.col("tag_time").desc()).select("event_id", "tag_type", "tag_time").show(3)
# ── 결과 ──
# +--------+--------+-------------------+
# |event_id|tag_type|           tag_time|
# +--------+--------+-------------------+
# |     M11|     OUT|2026-10-14 08:31:40|
# |     M10|     OUT|2026-10-14 08:29:00|
# |     M09|     OUT|2026-10-14 08:24:50|
# +--------+--------+-------------------+
# only showing top 3 rows
# → tag_time 은 지금 글자지만, 2026-10-14 08:31:40 처럼 자리 수가 같은 글자는 정렬해도 시각 순서와 같습니다.

# %% [06-8] 승차는 "승차", 하차는 "하차" 라고 적힌 구분 칸을 새로 만들어 보십시오.
mini.withColumn("구분", F.when(F.col("tag_type") == "IN", "승차").otherwise("하차")) \
    .select("event_id", "tag_type", "구분").show()
# ── 결과 ──
# +--------+--------+----+
# |event_id|tag_type|구분|
# +--------+--------+----+
# |     M01|      IN|승차|
# |     M02|      IN|승차|
# |     M03|      IN|승차|
# |     M04|      IN|승차|
# |     M05|      IN|승차|
# |     M06|      IN|승차|
# |     M07|     OUT|하차|
# |     M08|     OUT|하차|
# |     M09|     OUT|하차|
# |     M10|     OUT|하차|
# |     M11|     OUT|하차|
# |     M07|     OUT|하차|
# +--------+--------+----+
# → 줄 끝의 역슬래시(\) 는 "다음 줄에 이어진다" 입니다. 길어지면 점(.) 앞에서 끊어 씁니다.

# %% [06-9] 요금을 천 원 단위(소수 한 자리)로 바꾼 fare_k 칸을 만들고, 하차만 보십시오.
(mini.filter(F.col("tag_type") == "OUT")
     .withColumn("fare_k", F.round(F.col("fare") / 1000, 1))
     .select("trip_id", "fare", "fare_k")
     .show())
# ── 결과 ──
# +-------+----+------+
# |trip_id|fare|fare_k|
# +-------+----+------+
# |   T005|1550|   1.6|
# |   T003|1550|   1.6|
# |   T002|1650|   1.7|
# |   T004|1650|   1.7|
# |   T001|1650|   1.7|
# |   T005|1550|   1.6|
# +-------+----+------+
# → 전체를 괄호로 감싸면 역슬래시 없이 여러 줄에 쓸 수 있습니다. 점(.) 하나가 한 단계 — 위에서 아래로 읽습니다.

# %% [06-10] station_id 칸 이름을 역코드 로 바꿔 보여 주십시오.
mini.select(F.col("station_id").alias("역코드"), "tag_type").show(3)
